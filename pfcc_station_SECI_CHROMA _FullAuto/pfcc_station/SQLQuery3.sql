SELECT Top 200 BOX_BATT,K_Value,
CASE WHEN K_Value >= - 0.03 AND K_Value <= 0 THEN 'A' 
   WHEN K_Value >= 0 AND K_Value <= 0.03 THEN 'B' 
   WHEN K_Value >= - 0.06 AND K_Value <= - 0.03 THEN 'C' 
   WHEN K_Value >= 0.03 AND K_Value <= 0.06 THEN 'D' 
   WHEN K_Value >= - 0.1 AND K_Value <= - 0.06 THEN 'E' 
   WHEN K_Value >= 0.06 AND K_Value <= 0.1 THEN 'F' 
   WHEN K_Value < - 0.1 THEN 'G' 
   WHEN K_Value > 0.1 THEN 'H' ELSE 'NA' END AS ClassType 
  FROM HTBI_K_Value_MapperType2_V 
  WHERE 1 = 1 ORDER BY id DESC,ClassType;


